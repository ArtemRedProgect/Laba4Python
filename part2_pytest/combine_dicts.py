def combine_dicts(d1, d2):
    """Объединяет два словаря с сохранением порядка ключей.

    Args:
        d1 (dict): первый словарь.
        d2 (dict): второй словарь.

    Returns:
        dict: новый словарь; при совпадении ключей используется
              значение из d2. Исходные словари не изменяются.
    """
    result = dict(d1)
    result.update(d2)
    return result